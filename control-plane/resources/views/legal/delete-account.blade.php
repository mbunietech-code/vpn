<x-legal.layout title="Delete your account">
  <p>This page explains how to delete your <strong>Mbunie VPN</strong> account
  (by Mbunie Tech) and the data linked to it.</p>

  <h2>How to request deletion</h2>
  <ol>
    <li>Send an email to
      <a href="mailto:support@mbuniehub.com?subject=Delete%20my%20Mbunie%20VPN%20account">support@mbuniehub.com</a>
      with the subject <em>"Delete my Mbunie VPN account"</em>.</li>
    <li>Send it from the email address you sign in with, or include the phone
      number or email address of your account.</li>
    <li>We confirm the request and delete the account within 30 days.</li>
  </ol>

  <h2>What we delete</h2>
  <ul>
    <li>Your account identifier (email address or phone number)</li>
    <li>Your devices, their identifiers, models and OS versions, and their VPN keys</li>
    <li>Connection status, error reports and data usage totals</li>
    <li>The IP address recorded at sign-up</li>
  </ul>

  <h2>What we keep</h2>
  <p>Payment records are kept for as long as tax law requires (up to 7 years),
  then deleted. We never had records of your browsing, so there is nothing of
  that kind to delete.</p>
