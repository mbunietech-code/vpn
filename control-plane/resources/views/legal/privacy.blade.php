  <h2>1. We do not log your traffic</h2>
  <p>We do not keep records of the websites you visit, your DNS queries or the
  content of your traffic. Our servers are set up without content logs.</p>

  <h2>2. What we store</h2>
  <ul>
    <li>Your account identifier (phone number or email) so you can sign in</li>
    <li>Payment records (through the payment provider) and your plan's expiry date</li>
    <li>A device identifier, to apply the device limit of your plan</li>
    <li>Device model, operating system version, app version, whether the VPN is
      connected, and connection error messages — to show your devices and to fix problems</li>
    <li>Aggregate data usage (bytes) for operating the service — never content</li>
    <li>The IP address used at sign-up (to prevent abuse)</li>
  </ul>

  <h2>3. Third-party providers</h2>
  <p>ClickPesa, MbunieHub, Stripe and Cryptomus (payments), Brevo/SMTP (email) and
  Cloudflare (website hosting). None of them can see your VPN traffic.</p>

  <h2>4. How long we keep data</h2>
  <p>Account data is kept while your account exists. Payment records are kept as
  long as tax law requires.</p>

  <h2>5. Your rights</h2>
  <p>You can ask us to delete your account and its data by writing to
  <a href="mailto:support@mbuniehub.com">support@mbuniehub.com</a>.</p>

  <h2>6. Children</h2>
  <p>The service is not for people under 18.</p>
